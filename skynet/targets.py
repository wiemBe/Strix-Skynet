"""Turn a stored target into Strix inputs.

Strix has no dedicated options for scope or authentication; its documented mechanism is the
instruction text (--instruction / --instruction-file, https://docs.strix.ai/usage/instructions).
Scope and credentials are therefore rendered into a per-scan instruction file (0600, deleted after
the run). Note: anything in that file is part of the prompt and is sent to the selected LLM provider.
"""
from __future__ import annotations

from typing import Any

from . import crypto

ENVIRONMENTS = ("development", "test", "staging", "production")
AUTH_TYPES = ("none", "credentials", "header")


def strix_targets(t: dict[str, Any]) -> list[str]:
    out = [t["base_url"].strip()]
    for x in t.get("extra_targets") or []:
        x = str(x).strip()
        if x and x not in out:
            out.append(x)
    return out


def _bullets(items: list[str]) -> str:
    return "\n".join(f"- {i}" for i in items)


def instruction_text(t: dict[str, Any], extra_instruction: str = "", with_secrets: bool = True) -> str:
    """with_secrets=False produces the same text with credentials masked (for previews)."""
    parts = ["# Engagement context (generated by Skynet)",
             f"Application: {t.get('application') or t['name']}",
             f"Environment: {t['environment']}"]
    if t["environment"] == "production":
        parts.append("This is a PRODUCTION system. Do not run denial-of-service, load or brute-force tests, "
                     "do not modify or delete data, and stop exploitation once a vulnerability is confirmed.")
    in_scope = [s for s in (t.get("in_scope") or []) if s.strip()]
    if in_scope:
        parts += ["", "## Authorized scope", "Only the following hosts/URLs are authorized for testing:",
                  _bullets(in_scope)]
    out_scope = [s for s in (t.get("out_of_scope") or []) if s.strip()]
    if out_scope:
        parts += ["", "## Out of scope", "Do NOT send any traffic to the following hosts/URLs/paths:",
                  _bullets(out_scope)]
    if t.get("auth_type") and t["auth_type"] != "none":
        secret = crypto.decrypt(t.get("auth_secret_enc")) if with_secrets else "********"
        parts += ["", "## Authentication"]
        if t.get("auth_login_url"):
            parts.append(f"Login URL: {t['auth_login_url']}")
        if t["auth_type"] == "credentials":
            parts.append(f"Use these test credentials: username `{t.get('auth_username', '')}` / password `{secret}`")
        elif t["auth_type"] == "header":
            parts.append(f"Send this header on authenticated requests: `{t.get('auth_header_name', '')}: {secret}`")
        if t.get("auth_notes"):
            parts.append(t["auth_notes"].strip())
    instr = "\n\n".join(x.strip() for x in (t.get("instruction") or "", extra_instruction or "") if x and x.strip())
    if instr:
        parts += ["", "## Instructions", instr]
    return "\n".join(parts) + "\n"
