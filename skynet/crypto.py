"""Encryption at rest for secrets (LLM API keys, auth profiles / vault, CI token).

Key source, in order:
  1. SKYNET_SECRET_KEY (env)
  2. SKYNET_SECRET_KEY_FILE, default ~/.config/skynet/secret.key -- deliberately outside SKYNET_DATA so that a
     copy of the data folder (database backups etc.) cannot decrypt anything on its own.
A key generated by older versions at data/secret.key is moved to the new location on start (copied, verified,
then removed). The key is never regenerated while one exists. Losing the key makes stored secrets unreadable;
they then have to be re-entered in the UI.

Vault secrets use a sub-key derived from the master key (domain separation from LLM keys and cookies).
"""
from __future__ import annotations

import base64
from contextlib import closing
import hashlib
import hmac
import logging
import os
import sqlite3
from pathlib import Path

from cryptography.fernet import Fernet, InvalidToken

from .config import DATA_DIR, DB_PATH, LEGACY_SECRET_KEY_FILE, SECRET_KEY, SECRET_KEY_FILE, SECRET_KEY_FILE_FROM_ENV

log = logging.getLogger("skynet.crypto")
_status: dict[str, object] = {}


class DecryptError(Exception):
    """A stored secret exists but cannot be decrypted (wrong or rotated key)."""


def _write_key(path: Path, key: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        os.chmod(path.parent, 0o700)
    except OSError:
        pass
    tmp = path.with_name(path.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(key)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)


def _valid(key: bytes) -> bool:
    try:
        f = Fernet(key)
        return f.decrypt(f.encrypt(b"probe")) == b"probe"
    except (ValueError, InvalidToken):
        return False


def _inside_data(path: Path) -> bool:
    try:
        path.resolve().relative_to(DATA_DIR)
        return True
    except ValueError:
        return False


def _load_key() -> bytes:
    legacy = LEGACY_SECRET_KEY_FILE
    if SECRET_KEY:
        _status.update(source="env", path=None, legacy_present=legacy.exists())
        return SECRET_KEY.encode()
    target = SECRET_KEY_FILE
    _status.update(source="file", path=str(target), from_env=SECRET_KEY_FILE_FROM_ENV)
    if target.exists():
        key = target.read_bytes().strip()
        if legacy.exists() and legacy.resolve() != target.resolve():
            if legacy.read_bytes().strip() == key:
                legacy.unlink()
                log.info("removed duplicate legacy key %s", legacy)
            else:
                log.warning("legacy key %s differs from %s; left untouched", legacy, target)
        _status["legacy_present"] = legacy.exists() and legacy.resolve() != target.resolve()
        return key
    if legacy.exists():
        # Relocate: copy, verify the copy byte-for-byte and as a working Fernet key, then remove the original.
        key = legacy.read_bytes().strip()
        if not _valid(key):
            raise RuntimeError(f"{legacy} is not a valid Fernet key; refusing to move it")
        _write_key(target, key)
        if target.read_bytes().strip() != key or not _valid(target.read_bytes().strip()):
            raise RuntimeError(f"could not verify relocated key at {target}")
        legacy.unlink()
        _status.update(migrated_from=str(legacy), legacy_present=False)
        log.warning("encryption key moved from %s to %s (outside the data folder)", legacy, target)
        return key
    # A missing key with existing encrypted data is a recovery problem, not a first installation.
    # Refuse to replace it silently (also protects partially restored data directories).
    if DB_PATH.exists():
        with closing(sqlite3.connect(DB_PATH.resolve().as_uri() + "?mode=ro", uri=True)) as c:
            tables = {r[0] for r in c.execute("SELECT name FROM sqlite_master WHERE type='table'")}
            for table, column in (("llm_profiles", "api_key_enc"), ("targets", "auth_secret_enc"),
                                  ("auth_profiles", "secret_enc"), ("scans", "redact_enc"),
                                  ("agent_messages", "content_enc"), ("analyst_note_revisions", "body_enc")):
                cols = {r[1] for r in c.execute(f"PRAGMA table_info({table})")} if table in tables else set()
                if column in cols and c.execute(f"SELECT 1 FROM {table} WHERE COALESCE({column},'')<>'' LIMIT 1").fetchone():
                    raise RuntimeError("Encryption key is missing. A new key will not be generated while encrypted records exist. Restore the existing key.")
            if "settings" in tables and c.execute("SELECT 1 FROM settings WHERE key='api_token_enc' AND COALESCE(value,'')<>''").fetchone():
                raise RuntimeError("Encryption key is missing. Restore the existing key.")
    key = Fernet.generate_key()
    _write_key(target, key)
    _status["legacy_present"] = False
    return key


_key = _load_key()
_fernet = Fernet(_key)
_status["colocated"] = bool(_status.get("path")) and _inside_data(Path(str(_status["path"])))


def derive(label: str) -> bytes:
    """Independent sub-key (e.g. for session-cookie HMAC) derived from the master key."""
    return hmac.new(_key, label.encode(), hashlib.sha256).digest()


_vault = Fernet(base64.urlsafe_b64encode(derive("vault-v1")))


def key_status() -> dict[str, object]:
    """Where the key lives (never the key itself), for the settings page."""
    return dict(_status)


def encrypt(value: str) -> str:
    return _fernet.encrypt(value.encode()).decode() if value else ""


def decrypt(token: str | None) -> str:
    if not token:
        return ""
    try:
        return _fernet.decrypt(token.encode()).decode()
    except InvalidToken:
        return ""


def decrypt_strict(token: str | None) -> str:
    """Like decrypt(), but a present-yet-unreadable value raises instead of silently becoming ''."""
    if not token:
        return ""
    try:
        return _fernet.decrypt(token.encode()).decode()
    except InvalidToken as e:
        raise DecryptError("stored secret could not be decrypted (the encryption key may have changed)") from e


def vault_encrypt(value: str) -> str:
    return _vault.encrypt(value.encode()).decode() if value else ""


def vault_decrypt(token: str | None) -> str:
    if not token:
        return ""
    try:
        return _vault.decrypt(token.encode()).decode()
    except InvalidToken as e:
        raise DecryptError("authentication secret could not be decrypted (the encryption key may have changed)") from e
